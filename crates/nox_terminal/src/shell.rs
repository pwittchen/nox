//! Shell integration (SPEC §4.5): small snippets for zsh (`ZDOTDIR` shim), bash (`--rcfile`
//! shim) and fish (`XDG_DATA_DIRS` vendor conf) that report the working directory (OSC 7) and
//! prompt marks (OSC 133). Everything works without them; they make titles, "jump to prompt",
//! "Copy Last Output" and command-finished notifications precise.

use std::collections::HashMap;
use std::io;
use std::path::{Path, PathBuf};

const ZSH_ENV: &str = r#"# nox shell integration (zsh). Generated by nox; do not edit.
# Restore the user's ZDOTDIR, load their .zshenv, then install nox's hooks.
if [[ -n "${NOX_ZDOTDIR_SET-}" ]]; then
  ZDOTDIR="$NOX_ORIG_ZDOTDIR"
else
  unset ZDOTDIR
fi
unset NOX_ZDOTDIR_SET NOX_ORIG_ZDOTDIR
if [[ -f "${ZDOTDIR:-$HOME}/.zshenv" ]]; then
  source "${ZDOTDIR:-$HOME}/.zshenv"
fi
if [[ -o interactive && -n "${NOX_SHELL_INTEGRATION_DIR-}" ]]; then
  source "$NOX_SHELL_INTEGRATION_DIR/zsh/nox.zsh"
fi
"#;

const ZSH_HOOKS: &str = r#"# nox shell integration hooks (zsh). Generated by nox; do not edit.
autoload -Uz add-zsh-hook
typeset -g _nox_running=
_nox_urlencode() {
  local LC_ALL=C s="$1" out= c i
  for (( i = 1; i <= ${#s}; i++ )); do
    c="${s[i]}"
    case "$c" in
      [a-zA-Z0-9/._~-]) out+="$c" ;;
      *) out+=$(printf '%%%02X' "'$c") ;;
    esac
  done
  print -rn -- "$out"
}
_nox_precmd() {
  local ret=$?
  # rc files may reset PATH: keep the nox CLI reachable.
  if [[ -n "${NOX_BIN_DIR-}" && ":$PATH:" != *":$NOX_BIN_DIR:"* ]]; then
    PATH="$NOX_BIN_DIR:$PATH"
  fi
  if [[ -n "$_nox_running" ]]; then
    printf '\e]133;D;%s\a' "$ret"
    _nox_running=
  fi
  printf '\e]7;file://%s%s\a' "${HOST}" "$(_nox_urlencode "$PWD")"
  printf '\e]133;A\a'
}
_nox_preexec() {
  _nox_running=1
  printf '\e]133;C\a'
}
add-zsh-hook precmd _nox_precmd
add-zsh-hook preexec _nox_preexec
"#;

const BASH_RC: &str = r#"# nox shell integration (bash). Generated by nox; do not edit.
if [[ -n "${NOX_BASH_LOGIN-}" ]]; then
  unset NOX_BASH_LOGIN
  [[ -f /etc/profile ]] && source /etc/profile
  for _nox_f in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
    if [[ -f "$_nox_f" ]]; then source "$_nox_f"; break; fi
  done
  unset _nox_f
else
  [[ -f "$HOME/.bashrc" ]] && source "$HOME/.bashrc"
fi
_nox_running=
_nox_at_prompt=
_nox_prompt() {
  local ret=$?
  if [[ -n "${NOX_BIN_DIR-}" && ":$PATH:" != *":$NOX_BIN_DIR:"* ]]; then
    PATH="$NOX_BIN_DIR:$PATH"
  fi
  if [[ -n "$_nox_running" ]]; then
    printf '\e]133;D;%s\a' "$ret"
    _nox_running=
  fi
  printf '\e]7;file://%s%s\a' "$HOSTNAME" "${PWD// /%20}"
  printf '\e]133;A\a'
  _nox_at_prompt=1
  return $ret
}
_nox_preexec() {
  [[ -n "${COMP_LINE-}" ]] && return
  [[ -z "$_nox_at_prompt" ]] && return
  _nox_at_prompt=
  _nox_running=1
  printf '\e]133;C\a'
}
PROMPT_COMMAND="_nox_prompt${PROMPT_COMMAND:+; $PROMPT_COMMAND}"
trap '_nox_preexec' DEBUG
"#;

const FISH_CONF: &str = r"# nox shell integration (fish). Generated by nox; do not edit.
status is-interactive; or exit
function __nox_prompt --on-event fish_prompt
  set -l ret $status
  if set -q NOX_BIN_DIR; and not contains -- $NOX_BIN_DIR $PATH
    set -gx PATH $NOX_BIN_DIR $PATH
  end
  if set -q __nox_running
    printf '\e]133;D;%s\a' $ret
    set -e __nox_running
  end
  printf '\e]7;file://%s%s\a' (hostname) (string escape --style=url -- $PWD)
  printf '\e]133;A\a'
end
function __nox_preexec --on-event fish_preexec
  set -g __nox_running 1
  printf '\e]133;C\a'
end
";

/// Write the integration files into `dir` (idempotent; rewritten when the content changes).
pub fn install(dir: &Path) -> io::Result<()> {
    let files: [(&str, &str); 4] = [
        ("zsh/.zshenv", ZSH_ENV),
        ("zsh/nox.zsh", ZSH_HOOKS),
        ("bash/nox.bash", BASH_RC),
        ("fish/vendor_conf.d/nox.fish", FISH_CONF),
    ];
    for (rel, content) in files {
        let path = dir.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(content) {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, content)?;
    }
    Ok(())
}

/// How to start a shell with integration: possibly changed args plus extra environment.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Injection {
    pub args: Vec<String>,
    pub env: HashMap<String, String>,
}

/// Prepare the command line and environment for `shell` (path or name) so it loads nox's
/// integration from `dir`. Unknown shells get no injection.
#[must_use]
pub fn inject(dir: &Path, shell: &str, args: &[String]) -> Option<Injection> {
    let name = shell.rsplit('/').next().unwrap_or(shell).trim_start_matches('-');
    let mut env = HashMap::new();
    env.insert("NOX_SHELL_INTEGRATION_DIR".to_string(), dir.to_string_lossy().into_owned());
    match name {
        "zsh" => {
            if let Ok(orig) = std::env::var("ZDOTDIR") {
                env.insert("NOX_ZDOTDIR_SET".into(), "1".into());
                env.insert("NOX_ORIG_ZDOTDIR".into(), orig);
            }
            env.insert("ZDOTDIR".into(), dir.join("zsh").to_string_lossy().into_owned());
            Some(Injection { args: args.to_vec(), env })
        }
        "bash" => {
            // bash ignores --rcfile for login shells: drop -l / --login and let the rcfile load
            // the login files itself.
            let mut new_args: Vec<String> = Vec::new();
            let mut login = false;
            for a in args {
                if a == "-l" || a == "--login" {
                    login = true;
                } else {
                    new_args.push(a.clone());
                }
            }
            if login {
                env.insert("NOX_BASH_LOGIN".into(), "1".into());
            }
            let mut full =
                vec!["--rcfile".to_string(), dir.join("bash/nox.bash").to_string_lossy().into_owned()];
            full.extend(new_args);
            if !full.iter().any(|a| a == "-i") {
                full.push("-i".into());
            }
            Some(Injection { args: full, env })
        }
        "fish" => {
            let base = dir.join("fish").to_string_lossy().into_owned();
            let existing =
                std::env::var("XDG_DATA_DIRS").unwrap_or_else(|_| "/usr/local/share:/usr/share".into());
            env.insert("XDG_DATA_DIRS".into(), format!("{base}:{existing}"));
            Some(Injection { args: args.to_vec(), env })
        }
        _ => None,
    }
}

/// Default location of the generated files.
#[must_use]
pub fn default_dir(nox_dir: &Path) -> PathBuf {
    nox_dir.join("shell-integration")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn installs_files() {
        let d = tempfile::tempdir().unwrap();
        install(d.path()).unwrap();
        assert!(d.path().join("zsh/.zshenv").exists());
        assert!(d.path().join("fish/vendor_conf.d/nox.fish").exists());
        install(d.path()).unwrap();
    }

    #[test]
    fn bash_login_becomes_rcfile() {
        let d = Path::new("/x");
        let inj = inject(d, "/bin/bash", &["-l".into()]).unwrap();
        assert_eq!(inj.args, vec!["--rcfile", "/x/bash/nox.bash", "-i"]);
        assert_eq!(inj.env.get("NOX_BASH_LOGIN").map(String::as_str), Some("1"));
    }

    #[test]
    fn zsh_sets_zdotdir() {
        let inj = inject(Path::new("/x"), "zsh", &["-l".into()]).unwrap();
        assert_eq!(inj.env.get("ZDOTDIR").map(String::as_str), Some("/x/zsh"));
        assert_eq!(inj.args, vec!["-l"]);
        assert!(inject(Path::new("/x"), "/usr/bin/tcsh", &[]).is_none());
    }
}
